/** What a refusal means, in words. The backend's message is the fallback, never hidden. */
export function refusalText(refusal: DeploymentRefusal): string {
  if (refusal.code === 'operation_in_progress') {
    return 'A deployment is already pending or running for this application and environment. Wait for it to finish, or cancel it if it has not started.';
  }
  if (refusal.code === 'rate_limited') {
    return 'Too many deployments were requested in the last hour. Try again later.';
  }
  if (refusal.code === 'not_registered') {
    return 'No active deployment target is registered for this application and environment.';
  }
  if (refusal.code === 'not_permitted' && refusal.reason === 'ref_not_permitted') {
    return refusal.patterns.length > 0
      ? `That ref is not permitted. This target allows refs matching: ${refusal.patterns.join(', ')}.`
      : 'That ref is not permitted for this target.';
  }
  if (
    refusal.code === 'conflict' &&
    refusal.reason === 'idempotency_key_reused_with_different_payload'
  ) {
    return 'This request conflicts with one already sent. Close the dialog and start again.';
  }
  switch (refusal.reason) {
    case 'approval_workflow_unavailable':
      return 'This deployment needs an approval, and the approval workflow is not available yet, so it cannot be requested.';
    case 'jenkins_not_configured':
      return 'Jenkins is not configured on this deployment, so nothing can be deployed.';
    case 'demonstration_mode':
      return 'This portal is in demonstration mode. No deployment can run.';
    default:
      return refusal.message;
  }
}
