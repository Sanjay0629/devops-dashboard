/**
 * Deployments client (API_CONTRACTS.md §21.1 – §21.3, §21.6; PRD §4.10).
 *
 * `api/deployments.ts` is the registry of *targets*; this is the requests that run them.
 *
 * **The request carries four values and nothing else:** an application, an environment, a ref and
 * a reason. There is no parameter through which a Jenkins URL, a job path, a build parameter or a
 * node label could travel, and `requestDeployment` takes them one by one rather than as an object
 * a caller could add to. The pipeline and its parameters come from the registered target on the
 * backend, which decides every request and decides it again in the worker.
 *
 * What this file adds to `Result` is the part it cannot say: a **refusal** (`503 not_configured`,
 * `422 not_registered` / `not_permitted`, `409 operation_in_progress`, `429`) carries a closed
 * reason the person at the dialog needs in words. `Result` would fold a deliberate `503` into
 * "could not reach the backend", which for a request the backend answered would be a lie.
 */

