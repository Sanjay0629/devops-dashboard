/** A deliberate answer from the backend that nothing was created, with its closed reason. */
export interface DeploymentRefusal {
  kind: 'refused';
  status: number;
  code: string;
  reason: string | null;
  message: string;
  /** The patterns a refused ref was checked against (`not_permitted` only), else empty. */
  patterns: string[];
}

export type Requested =
  | { kind: 'ok'; deployment: DeploymentAccepted; replayed: boolean }
  | DeploymentRefusal
  | Exclude<Result<never>, { kind: 'ok' }>;

interface ErrorBody {
  error?: {
    code?: string;
    message?: string;
    details?: { reason?: unknown; allowed_ref_patterns?: unknown };
  };
}

function isRecord(value: unknown): value is Record<string, unknown> {
  return typeof value === 'object' && value !== null;
}

const isAccepted = (value: unknown): value is DeploymentAccepted =>
  isRecord(value) && typeof value.deployment_id === 'string';

/**
 * §21.2. `key` is generated by the caller once per dialog, so a second click re-sends the same
 * intent and the backend answers with the original instead of starting another.
 */
export async function requestDeployment(
  applicationId: string,
  environment: string,
  ref: string,
  reason: string | null,
  key: string = idempotencyKey(),
): Promise<Requested> {
  const body = {
    application_id: applicationId,
    environment,
    ref,
    ...(reason === null ? {} : { reason }),
  };
  try {
    const response = await request('/deployments', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json', 'Idempotency-Key': key },
      body: JSON.stringify(body),
    });
    if (response.ok) {
      const accepted: unknown = await response.json();
      if (!isAccepted(accepted))
        return { kind: 'unreachable', reason: 'Unexpected response shape' };
      return { kind: 'ok', deployment: accepted, replayed: response.status === 200 };
    }
    if (response.status === 403) return { kind: 'forbidden' };
    if (response.status === 404) return { kind: 'not_found' };
    if (response.status === 423) return { kind: 'read_only' };
    let parsed: ErrorBody = {};
    try {
      parsed = (await response.json()) as ErrorBody;
    } catch {
      return { kind: 'unreachable', reason: `Unexpected status ${String(response.status)}` };
    }
    const code = parsed.error?.code ?? '';
    const message = parsed.error?.message ?? `Unexpected status ${String(response.status)}`;
    if (response.status === 422 && code === 'validation_failed') {
      return { kind: 'invalid', problems: [], message };
    }
    if ([409, 422, 429, 503].includes(response.status)) {
      const reason = parsed.error?.details?.reason;
      const patterns = parsed.error?.details?.allowed_ref_patterns;
      return {
        kind: 'refused',
        status: response.status,
        code,
        reason: typeof reason === 'string' ? reason : null,
        message,
        patterns: Array.isArray(patterns)
          ? patterns.filter((p): p is string => typeof p === 'string')
          : [],
      };
    }
    return { kind: 'unreachable', reason: message };
  } catch (error) {
    return {
      kind: 'unreachable',
      reason: error instanceof Error ? error.message : 'Request failed',
    };
  }
}

const isDetail = (value: unknown): boolean =>
  isRecord(value) && typeof value.deployment_id === 'string';

/** §21.3. */
export function readDeployment(id: string): Promise<Result<DeploymentDetail>> {
  return call(`/deployments/${encodeURIComponent(id)}`, {}, isDetail);
}

/** §21.6. A `409` means a worker got there first, and is shown as such rather than retried. */
export function cancelDeployment(id: string): Promise<Result<DeploymentDetail>> {
  return call(`/deployments/${encodeURIComponent(id)}/cancel`, { method: 'POST' }, isDetail);
}

export interface DeploymentFilters {
  statuses: DeploymentStatus[];
  environments: string[];
  applicationId: string;
  /** A UUID. `requested_by` narrows to one person's requests and cannot widen scope. */
  requestedBy: string;
  /** RFC 3339 with an offset, or empty for the backend's default (the last 7 days). */
  from: string;
  to: string;
  cursor?: string | undefined;
}

export const EMPTY_FILTERS: DeploymentFilters = {
  statuses: [],
  environments: [],
  applicationId: '',
  requestedBy: '',
  from: '',
  to: '',
};

/** Repeats a parameter per value, which the API takes for lists. Sends only what was given. */
export function deploymentQuery(filters: DeploymentFilters): string {
  const params = new URLSearchParams();
  for (const status of filters.statuses) params.append('execution_status', status);
  for (const environment of filters.environments) params.append('environment', environment);
  if (filters.applicationId !== '') params.set('application_id', filters.applicationId);
  if (filters.requestedBy !== '') params.set('requested_by', filters.requestedBy);
  if (filters.from !== '') params.set('from', filters.from);
  if (filters.to !== '') params.set('to', filters.to);
  if (filters.cursor !== undefined) params.set('cursor', filters.cursor);
  const text = params.toString();
  return text === '' ? '' : `?${text}`;
}

const isList = (value: unknown): boolean =>
  isRecord(value) && Array.isArray(value.items) && isRecord(value.page);

/** §21.1. */
export function listDeployments(filters: DeploymentFilters): Promise<Result<DeploymentList>> {
  return call<DeploymentList>(`/deployments${deploymentQuery(filters)}`, {}, isList);
}

