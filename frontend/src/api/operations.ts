/**
 * Service operations client (API_CONTRACTS.md §17).
 *
 * Shapes are the generated ones. What this file adds is the part `Result` cannot say: a
 * **refusal** (`503 not_configured`, `422 unsupported_operation`, `409`, `429`) carries a closed
 * `details.reason` that the person looking at the dialog needs in words. `Result` folds a `503`
 * into "could not reach the backend", which for a request the backend answered deliberately
 * would be a lie about what happened.
 *
 * Nothing here authorises anything, and nothing here can send a command: the request body is the
 * closed action enum and a reason, exactly as the backend's model is.
 */

import { call, idempotencyKey, type Result } from '@/api/inventory';
import type { components } from '@/api/schema';
import { request } from '@/api/session';

type Schemas = components['schemas'];

export type OperationAccepted = Schemas['OperationAccepted'];
export type OperationDetail = Schemas['OperationDetail'];
export type OperationStatus = OperationDetail['execution_status'];
/** The three actions §17.1 accepts. `status` and `logs_tail` have their own endpoints. */
export type OperationAction = 'start' | 'stop' | 'restart';

export const REQUESTABLE_ACTIONS: readonly OperationAction[] = ['start', 'stop', 'restart'];

export const TERMINAL: readonly OperationStatus[] = [
  'SUCCEEDED',
  'FAILED',
  'TIMED_OUT',
  'CANCELLED',
  'REJECTED',
];

/** Cancelling is legal only before a worker has claimed the row (§17.3). */
export const CANCELLABLE: readonly OperationStatus[] = ['PENDING', 'AWAITING_APPROVAL'];

/** A deliberate answer from the backend that nothing was created, with its closed reason. */
export interface Refusal {
  kind: 'refused';
  status: number;
  code: string;
  reason: string | null;
  message: string;
}

export type Requested =
  | { kind: 'ok'; operation: OperationAccepted; replayed: boolean }
  | Refusal
  | Exclude<Result<never>, { kind: 'ok' }>;

interface ErrorBody {
  error?: { code?: string; message?: string; details?: { reason?: unknown } };
}

function isAccepted(value: unknown): value is OperationAccepted {
  return (
    typeof value === 'object' &&
    value !== null &&
    typeof (value as { operation_id?: unknown }).operation_id === 'string'
  );
}

/**
 * §17.1. `key` is generated by the caller once per dialog, so a second click re-sends the same
 * intent and the backend answers with the original instead of starting another.
 */
export async function requestOperation(
  serverId: string,
  serviceName: string,
  action: OperationAction,
  reason: string | null,
  key: string = idempotencyKey(),
): Promise<Requested> {
  try {
    const response = await request(
      `/servers/${encodeURIComponent(serverId)}/services/${encodeURIComponent(serviceName)}/operations`,
      {
        method: 'POST',
        headers: { 'Content-Type': 'application/json', 'Idempotency-Key': key },
        body: JSON.stringify(reason === null ? { action } : { action, reason }),
      },
    );
    if (response.ok) {
      const body: unknown = await response.json();
      if (!isAccepted(body)) return { kind: 'unreachable', reason: 'Unexpected response shape' };
      return { kind: 'ok', operation: body, replayed: response.status === 200 };
    }
    if (response.status === 403) return { kind: 'forbidden' };
    if (response.status === 404) return { kind: 'not_found' };
    if (response.status === 423) return { kind: 'read_only' };
    let body: ErrorBody = {};
    try {
      body = (await response.json()) as ErrorBody;
    } catch {
      return { kind: 'unreachable', reason: `Unexpected status ${String(response.status)}` };
    }
    const code = body.error?.code ?? '';
    const message = body.error?.message ?? `Unexpected status ${String(response.status)}`;
    if (response.status === 422 && code === 'validation_failed') {
      return { kind: 'invalid', problems: [], message };
    }
    if ([409, 422, 429, 503].includes(response.status)) {
      const reason = body.error?.details?.reason;
      return {
        kind: 'refused',
        status: response.status,
        code,
        reason: typeof reason === 'string' ? reason : null,
        message,
      };
    }
    return { kind: 'unreachable', reason: message };
  } catch (error) {
    return {
      kind: 'unreachable',
      reason: error instanceof Error ? error.message : 'Request failed',
    };
  }
}

const isDetail = (value: unknown): boolean =>
  typeof value === 'object' &&
  value !== null &&
  typeof (value as { operation_id?: unknown }).operation_id === 'string';

/** §17.2. */
export function readOperation(id: string): Promise<Result<OperationDetail>> {
  return call(`/operations/${encodeURIComponent(id)}`, {}, isDetail);
}

/** §17.3. A `409` means a worker got there first, and is shown as such rather than retried. */
export function cancelOperation(id: string): Promise<Result<OperationDetail>> {
  return call(`/operations/${encodeURIComponent(id)}/cancel`, { method: 'POST' }, isDetail);
}

/** What a refusal means, in words. The backend's message is the fallback, never hidden. */
export function refusalText(refusal: Refusal): string {
  if (refusal.code === 'operation_in_progress') {
    return 'Another operation is already pending or running for this service. Wait for it to finish, or cancel it.';
  }
  if (refusal.code === 'unsupported_operation') {
    return 'This action is not supported by this server’s provider.';
  }
  if (refusal.code === 'rate_limited') {
    return 'Too many operations were requested in the last minute. Try again shortly.';
  }
  if (
    refusal.code === 'conflict' &&
    refusal.reason === 'idempotency_key_reused_with_different_payload'
  ) {
    return 'This request conflicts with one already sent. Close the dialog and start again.';
  }
  switch (refusal.reason) {
    case 'demonstration_mode':
      return 'This portal is in demonstration mode. No operation can run.';
    case 'no_adapter_for_provider':
      return 'No provider integration is configured for this server’s cloud account, so nothing can act on it yet.';
    case 'approval_workflow_unavailable':
      return 'This operation needs an approval, and the approval workflow is not available yet, so it cannot be requested.';
    case 'cloud_account_not_active':
      return 'This server’s cloud account is not active.';
    default:
      return refusal.message;
  }
}

/** The closed `failure_reason` codes, as words. An unknown code is shown as itself. */
const FAILURES: Record<string, string> = {
  PERMISSION_REVOKED: 'The requester no longer has permission for this action.',
  APPROVAL_REQUIRED: 'An approval is required and was not recorded.',
  ACCOUNT_DISABLED: 'The cloud account was disabled before the operation started.',
  ACTION_NOT_ALLOWED: 'The service’s policy no longer allows this action.',
  TARGET_VALIDATION_FAILED:
    'The target no longer matched what was requested (the server, service or environment changed, or the provider no longer knows it).',
  NOT_CONFIGURED: 'No provider integration was available when the operation started.',
  UNSUPPORTED_OPERATION: 'The provider does not support this action.',
  PROVIDER_AUTHENTICATION: 'The provider rejected DCP’s credentials.',
  PROVIDER_AUTHORIZATION: 'The provider denied the request.',
  PROVIDER_NOT_FOUND: 'The provider no longer has this resource.',
  PROVIDER_THROTTLED: 'The provider is rate limiting requests.',
  PROVIDER_TIMEOUT: 'The provider did not answer in time.',
  PROVIDER_UNAVAILABLE: 'The provider was unavailable.',
  PROVIDER_PARTIAL_FAILURE: 'The provider succeeded on some targets and failed on others.',
  PROVIDER_REPORTED_FAILURE: 'The provider reported that the operation failed.',
  VERIFICATION_MISMATCH: 'The provider finished, but the service is not in the state requested.',
  VERIFICATION_UNAVAILABLE:
    'The service’s state could not be read back, so the result is unproven.',
  DEADLINE_EXCEEDED: 'The operation did not finish before its deadline.',
  EXPIRED_BEFORE_START: 'The deadline passed before a worker picked the operation up.',
};

export function failureText(code: string | null | undefined): string {
  if (code == null || code === '') return '';
  return FAILURES[code] ?? code;
}
