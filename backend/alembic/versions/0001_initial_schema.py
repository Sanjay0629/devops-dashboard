def _apply_audit_immutability_grant() -> None:
    """Make the audit trail append-only (AD-11), in two independent layers.

    **Layer 1 — grants.** Revoke UPDATE/DELETE/TRUNCATE from the application
    role, leaving INSERT and SELECT.

    Grants alone are not enough, and this was verified rather than assumed: with
    the single database user of a development stack, the application role is the
    table *owner* and frequently a *superuser*, and a superuser bypasses
    privilege checks entirely. Measured directly against PostgreSQL 17.2 — the
    privileges showed as revoked in information_schema while UPDATE, DELETE and
    TRUNCATE all still succeeded. A control that reports success while doing
    nothing is worse than no control.

    **Layer 2 — triggers.** A BEFORE trigger is enforced for *every* role,
    superusers included, so UPDATE and DELETE raise regardless of who attempts
    them. TRUNCATE needs its own statement-level trigger, since row triggers
    never see it.

    A superuser can still drop the triggers — but a superuser can also drop the
    table, so that is the boundary of what any in-database mechanism can offer.
    Layer 2 stops accidental writes, ORM mistakes and a compromised application
    role that lacks DDL rights. The remaining hardening is a non-superuser
    application role separate from the migration owner, plus export to an
    independently protected store; both are scheduled for M6.2 (OPEN-15).
    """
    # Layer 1: grants. Correct and sufficient once the application connects as
    # a dedicated non-superuser role; inert before then, hence layer 2.
    op.execute("REVOKE UPDATE, DELETE, TRUNCATE ON audit_events FROM CURRENT_USER")
    op.execute("GRANT INSERT, SELECT ON audit_events TO CURRENT_USER")

    # Layer 2: triggers, which no role bypasses.
    op.execute(
        """
        CREATE OR REPLACE FUNCTION audit_events_reject_mutation()
        RETURNS TRIGGER AS $$
        BEGIN
            RAISE EXCEPTION
                'audit_events is append-only: % is not permitted (AD-11)',
                TG_OP
                USING ERRCODE = 'insufficient_privilege';
        END;
        $$ LANGUAGE plpgsql
        """
    )
    op.execute(
        """
        CREATE TRIGGER trg_audit_events_no_update_delete
        BEFORE UPDATE OR DELETE ON audit_events
        FOR EACH ROW EXECUTE FUNCTION audit_events_reject_mutation()
        """
    )
    op.execute(
        """
        CREATE TRIGGER trg_audit_events_no_truncate
        BEFORE TRUNCATE ON audit_events
        FOR EACH STATEMENT EXECUTE FUNCTION audit_events_reject_mutation()
        """
    )


