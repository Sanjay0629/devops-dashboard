def upgrade() -> None:
    connection = op.get_bind()

    # --- roles ---------------------------------------------------------------
    for name, description in ROLES:
        connection.execute(
            sa.text(
                """
                INSERT INTO roles (id, name, description, is_system,
                                   created_at, updated_at)
                VALUES (gen_random_uuid(), :name, :description, true, now(), now())
                ON CONFLICT (name) DO NOTHING
                """
            ),
            {"name": name, "description": description},
        )

    # --- permission catalogue ------------------------------------------------
    for resource_type, action, description in PERMISSIONS:
        connection.execute(
            sa.text(
                """
                INSERT INTO permissions (id, resource_type, action,
                                         scope_definition, description, created_at)
                VALUES (gen_random_uuid(), :resource_type, :action,
                        '{}'::jsonb, :description, now())
                ON CONFLICT (resource_type, action, scope_definition) DO NOTHING
                """
            ),
            {
                "resource_type": resource_type,
                "action": action,
                "description": description,
            },
        )

    # --- role -> permission --------------------------------------------------
    for role_name, grants in ROLE_PERMISSIONS.items():
        for resource_type, action in grants:
            connection.execute(
                sa.text(
                    """
                    INSERT INTO role_permissions (role_id, permission_id, effect,
                                                  created_at)
                    SELECT r.id, p.id, 'ALLOW', now()
                      FROM roles r
                      JOIN permissions p
                        ON p.resource_type = :resource_type
                       AND p.action = :action
                     WHERE r.name = :role_name
                    ON CONFLICT (role_id, permission_id) DO NOTHING
                    """
                ),
                {
                    "role_name": role_name,
                    "resource_type": resource_type,
                    "action": action,
                },
            )

    # --- the ON_PREM container for non-cloud servers -------------------------
    connection.execute(
        sa.text(
            """
            INSERT INTO cloud_accounts (id, provider, account_reference,
                                        display_name, region_configuration,
                                        status, created_at, updated_at)
            VALUES (gen_random_uuid(), 'ON_PREM', 'on-prem',
                    'On-premises and unmanaged servers', '{}'::jsonb,
                    'ACTIVE', now(), now())
            ON CONFLICT DO NOTHING
            """
        )
    )

    # --- approval policies ---------------------------------------------------
    # Production is gated by default. An environment that is not listed here has
    # no policy, and the operations layer treats "no policy" as "no approval
    # required" — so adding a policy is how an environment becomes protected.
    for name, environment, applies_to in (
        ("production-service-operations", "production", "SERVICE_OPERATION"),
        ("production-deployments", "production", "DEPLOYMENT"),
    ):
        connection.execute(
            sa.text(
                """
                INSERT INTO approval_policies (id, name, environment, applies_to,
                                               required_approvals,
                                               allow_self_approval, required_role,
                                               approval_window_seconds,
                                               created_at, updated_at)
                VALUES (gen_random_uuid(), :name, :environment, :applies_to,
                        1, false, 'APPROVER', 3600, now(), now())
                ON CONFLICT (name) DO NOTHING
                """
            ),
            {"name": name, "environment": environment, "applies_to": applies_to},
        )

    # --- service action policies ---------------------------------------------
    # 'read-only' is the conservative default: a service registered without an
    # explicit policy gets no actions at all, and this policy makes that
    # explicit for the cases where read-only is the intent.
    connection.execute(
        sa.text(
            """
            INSERT INTO service_action_policies (id, name, allowed_actions,
                                                 approval_policy_id,
                                                 max_concurrent_operations,
                                                 operation_timeout_seconds,
                                                 created_at, updated_at)
            VALUES (gen_random_uuid(), 'read-only',
                    ARRAY['status','logs_tail']::varchar[], NULL, 1, 300,
                    now(), now())
            ON CONFLICT (name) DO NOTHING
            """
        )
    )
    # 'restart-only' covers the common case from PRD §4.6 without granting the
    # ability to stop a service and leave it down.
    connection.execute(
        sa.text(
            """
            INSERT INTO service_action_policies (id, name, allowed_actions,
                                                 approval_policy_id,
                                                 max_concurrent_operations,
                                                 operation_timeout_seconds,
                                                 created_at, updated_at)
            SELECT gen_random_uuid(), 'restart-only',
                   ARRAY['status','logs_tail','restart']::varchar[],
                   ap.id, 1, 300, now(), now()
              FROM approval_policies ap
             WHERE ap.name = 'production-service-operations'
            ON CONFLICT (name) DO NOTHING
            """
        )
    )


