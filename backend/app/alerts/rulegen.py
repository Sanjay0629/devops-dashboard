"""Generate the Prometheus rule file from the two threshold settings (``OPEN-46``).

Pure: tables in, text out, no clock and no I/O. ``scripts/gen_alert_rules.py`` is the
command-line wrapper; ``check-all.sh`` runs it with ``--check`` so a stale committed
file fails the build, which is what keeps alert rules file-managed in git (``OPEN-03``)
and still leaves exactly one copy of the numbers.

**The expressions are the metric catalogue's own** (:data:`app.metrics.templates.CATALOGUE`),
with ``$selector`` replaced by one environment, so an alert and the chart beside it
cannot disagree about what "CPU" is.

**Warning and critical are mutually exclusive**: the warning rule is
``(value >= warning) unless (value >= critical)``. That is what lets a row's lifecycle
follow its own rule without a race when one batch carries a resolved warning and a
firing critical (``OPEN-41``).

**Server not reporting** fires after the environment's ``stale_after_seconds``
(``DCP_HEALTH_THRESHOLDS``), the moment the dashboard stops calling the host current: one
meaning, one number.

The output is YAML written by hand because every string is emitted as a JSON string,
which is a valid YAML double-quoted scalar; that keeps PromQL and Go-template text
intact without a YAML dependency.
"""

from __future__ import annotations

import json
from string import Template
from typing import Final

from app.alerts.catalogue import (
    BY_NAME,
    CPU_FOR_SECONDS,
    DISK_FOR_SECONDS,
    MEMORY_FOR_SECONDS,
    UNIT_FAILED_FOR_SECONDS,
    WATCHDOG_RULE,
)
from app.approvals.models import ENVIRONMENTS
from app.metrics.templates import BY_ID, DEFAULT_WINDOW_SECONDS, LINUX, NODE_JOB
from app.monitoring.health import HealthThresholdTable
from app.monitoring.utilisation import UtilisationThresholdTable

HEADER: Final = """\
# GENERATED by scripts/gen_alert_rules.py -- do not edit by hand.
#
# Source of the numbers: DCP_UTILISATION_THRESHOLDS (CPU, memory, disk) and
# DCP_HEALTH_THRESHOLDS (how long a host may be silent), over the metric catalogue's
# shipped defaults. Source of the expressions: app/metrics/templates.py. Source of the
# rule names: app/alerts/catalogue.py. `check-all.sh` fails when this file is stale.
# Regenerate with:  cd backend && uv run python ../scripts/gen_alert_rules.py
#
# Warning and critical are mutually exclusive on purpose (OPEN-41).
# `for:` durations are working defaults, not measurements (OPEN-46).
"""

_UTILISATION: Final = (
    ("cpu_utilisation", "cpu", "HostCpu", "CPU", CPU_FOR_SECONDS),
    ("memory_utilisation", "memory", "HostMemory", "Memory", MEMORY_FOR_SECONDS),
    ("disk_utilisation", "disk", "HostDisk", "Disk", DISK_FOR_SECONDS),
)


def _scalar(value: str) -> str:
    return json.dumps(value, ensure_ascii=True)


def _seconds(value: int) -> str:
    return f"{value}s"


def _number(value: float) -> str:
    return f"{value:g}"


def _expr(template_id: str, environment: str) -> str:
    """The catalogue's Linux expression, scoped to one environment's hosts."""
    query = BY_ID[template_id].queries[LINUX]
    return Template(query).substitute(
        selector=f'job="{NODE_JOB}",environment="{environment}"',
        window=f"{DEFAULT_WINDOW_SECONDS}s",
    )


def _rule(
    *,
    name: str,
    expr: str,
    for_seconds: int,
    condition: str,
    environment: str,
    summary: str,
) -> list[str]:
    severity = BY_NAME[name].severity.lower()
    return [
        f"      - alert: {name}",
        f"        expr: {_scalar(expr)}",
        f"        for: {_seconds(for_seconds)}",
        "        labels:",
        f"          severity: {severity}",
        f"          condition: {condition}",
        f"          environment: {environment}",
        "        annotations:",
        f"          summary: {_scalar(summary)}",
    ]


def _environment_rules(
    environment: str,
    utilisation: UtilisationThresholdTable,
    health: HealthThresholdTable,
) -> list[str]:
    lines_for = utilisation.for_environment(environment)
    lines: list[str] = [f"  - name: dcp-{environment}", "    rules:"]

    stale_after = health.for_environment(environment).stale_after_seconds
    lines += _rule(
        name="HostNotReporting",
        expr=f'up{{job="{NODE_JOB}",environment="{environment}"}} == 0',
        for_seconds=stale_after,
        condition="host_not_reporting",
        environment=environment,
        summary="Host {{ $labels.instance }} has stopped reporting",
    )

    for template_id, condition, prefix, label, for_seconds in _UTILISATION:
        line = lines_for[template_id]
        value = _expr(template_id, environment)
        warning = (
            f"({value} >= {_number(line.warning)}) unless ({value} >= {_number(line.critical)})"
        )
        critical = f"{value} >= {_number(line.critical)}"
        lines += _rule(
            name=f"{prefix}Warning",
            expr=warning,
            for_seconds=for_seconds,
            condition=condition,
            environment=environment,
            summary=(
                f"{label} on {{{{ $labels.instance }}}} is at "
                f'{{{{ $value | printf "%.1f" }}}}% (warning at {_number(line.warning)}%)'
            ),
        )
        lines += _rule(
            name=f"{prefix}Critical",
            expr=critical,
            for_seconds=for_seconds,
            condition=condition,
            environment=environment,
            summary=(
                f"{label} on {{{{ $labels.instance }}}} is at "
                f'{{{{ $value | printf "%.1f" }}}}% (critical at {_number(line.critical)}%)'
            ),
        )

    lines += _rule(
        name="SystemdUnitFailed",
        expr=(
            f'node_systemd_unit_state{{job="{NODE_JOB}",environment="{environment}",'
            'state="failed",name=~".+\\\\.service"} == 1'
        ),
        for_seconds=UNIT_FAILED_FOR_SECONDS,
        condition="unit_failed",
        environment=environment,
        summary="Unit {{ $labels.name }} on {{ $labels.instance }} has failed",
    )
    return lines


def render(
    utilisation: UtilisationThresholdTable | None = None,
    health: HealthThresholdTable | None = None,
) -> str:
    """The complete rule file for these thresholds."""
    utilisation = utilisation or UtilisationThresholdTable()
    health = health or HealthThresholdTable()
    out = [HEADER, "groups:"]
    out += [
        "  - name: dcp-watchdog",
        "    rules:",
        f"      - alert: {WATCHDOG_RULE}",
        f"        expr: {_scalar('vector(1)')}",
        "        labels:",
        "          severity: none",
        "        annotations:",
        f"          summary: {_scalar('Always firing: proves rule evaluation and delivery work')}",
    ]
    for environment in ENVIRONMENTS:
        out += _environment_rules(environment, utilisation, health)
    return "\n".join(out) + "\n"
